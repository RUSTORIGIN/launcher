# Builds config\piece-hashes.txt: the SHA-256 of every 32 MB piece of each hosted download (the full
# client zip and the delta pack). The launcher embeds this list; when a downloaded file fails its final
# SHA-256 check, it uses the list to find the damaged pieces and fetches only those again, instead of
# throwing the whole download away. Each piece is also checked as it arrives.
#
#   .\scripts\make_piece_hashes.ps1 C:\pack\RustClient-2021-04.zip C:\pack\RustClient-2021-01-to-2021-04.patchpack
#
# Run it on the exact files you upload, whenever the client zip or the pack changes, then rebuild the
# launcher. A file missing from the list (or a stale list) is harmless: that download just works without
# piece repair. Pieces must stay 32 MB to match ChunkSize in WpfLauncher.cs.
param([Parameter(Mandatory = $true, ValueFromRemainingArguments = $true)][string[]]$Files)
$ErrorActionPreference = 'Stop'
$repo  = Split-Path $PSScriptRoot -Parent
$out   = Join-Path $repo 'config\piece-hashes.txt'
$piece = 32MB

$lines = New-Object System.Collections.Generic.List[string]
$lines.Add('# SHA-256 of every 32 MB piece of each hosted download, so the launcher can fetch a damaged')
$lines.Add('# piece again on its own. Generated by scripts\make_piece_hashes.ps1 - do not edit by hand.')
$lines.Add('# One block per file:  file <full sha256> <size> <piece size>  then one hash per piece.')

function Hex([byte[]]$b) { ([BitConverter]::ToString($b) -replace '-', '').ToLowerInvariant() }

foreach ($f in $Files) {
    $path = (Resolve-Path $f).Path
    $size = (Get-Item $path).Length
    Write-Host "hashing $path ($([math]::Round($size / 1GB, 2)) GB)..."
    $full = [System.Security.Cryptography.SHA256]::Create()
    $hashes = New-Object System.Collections.Generic.List[string]
    $buf = New-Object byte[] (1MB)
    $fs = [System.IO.File]::OpenRead($path)
    try {
        while ($fs.Position -lt $size) {
            $p = [System.Security.Cryptography.SHA256]::Create()
            $left = [math]::Min($piece, $size - $fs.Position)
            while ($left -gt 0) {
                $n = $fs.Read($buf, 0, [int][math]::Min($buf.Length, $left))
                if ($n -le 0) { throw "unexpected end of $path" }
                [void]$p.TransformBlock($buf, 0, $n, $null, 0)
                [void]$full.TransformBlock($buf, 0, $n, $null, 0)
                $left -= $n
            }
            [void]$p.TransformFinalBlock($buf, 0, 0)
            $hashes.Add((Hex $p.Hash))
        }
    } finally { $fs.Dispose() }
    [void]$full.TransformFinalBlock($buf, 0, 0)
    $lines.Add("file $(Hex $full.Hash) $size $piece")
    $lines.AddRange($hashes)
    Write-Host "  $($hashes.Count) pieces, sha256 $(Hex $full.Hash)"
}

[System.IO.File]::WriteAllLines($out, $lines)
Write-Host "wrote $out - check each sha256 above matches launcher.cfg (Sha256 / PatchSha256), then rebuild the launcher."
